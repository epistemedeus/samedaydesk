import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it } from "node:test";
import { ensureUsefulJobsKit } from "../../../../server/paid-useful-jobs/lib/engine.mjs";
import { DEFAULT_CORPUS, REPO_ROOT } from "../lib/pins.mjs";
import { runCorpus } from "../lib/run-corpus.mjs";
import { compareDomain } from "../lib/compare.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const cli = join(here, "../bin/corpus.mjs");

function sha256(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

function collectFiles(dir, into = []) {
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, name.name);
    if (name.isDirectory()) collectFiles(p, into);
    else if (name.isFile()) into.push(p);
  }
  return into;
}

function runCli(argv, timeoutMs = 180_000) {
  return spawnSync(process.execPath, [cli, ...argv], {
    encoding: "utf8",
    cwd: REPO_ROOT,
    timeout: timeoutMs,
    maxBuffer: 8 * 1024 * 1024,
  });
}

describe("independent caller inputs", { timeout: 180_000 }, () => {
  it("shipped caller files are not byte copies of kit SAMPLE pricing/feed files", () => {
    const kit = ensureUsefulJobsKit();
    const kitHashes = new Set(
      collectFiles(join(kit, "samples")).map((p) => sha256(readFileSync(p))),
    );
    const shipped = collectFiles(DEFAULT_CORPUS).filter((p) => !p.endsWith("corpus.json") && !p.endsWith("case.json"));
    assert.ok(shipped.length >= 6);
    for (const file of shipped) {
      const digest = sha256(readFileSync(file));
      assert.equal(kitHashes.has(digest), false, `shipped ${file} matches a kit sample`);
    }
  });

  it("runtime-generated caller corpus is valid and differs from shipped raise output", () => {
    const work = mkdtempSync(join(tmpdir(), "w5-m11-runtime-"));
    mkdirSync(join(work, "fresh"));
    writeFileSync(
      join(work, "fresh/before.json"),
      `${JSON.stringify({
        label: "caller",
        note: "Runtime-only pair generated by the test.",
        rows: [
          { field: "runtime-batch", value: 9, unit: "USD/1K-jobs" },
          { field: "runtime-seat", value: 1, unit: "USD/seat-day" },
        ],
      })}\n`,
    );
    writeFileSync(
      join(work, "fresh/after.json"),
      `${JSON.stringify({
        label: "caller",
        note: "Runtime-only pair generated by the test.",
        rows: [
          { field: "runtime-batch", value: 11, unit: "USD/1K-jobs" },
          { field: "runtime-seat", value: 1, unit: "USD/seat-month" },
        ],
      })}\n`,
    );
    writeFileSync(
      join(work, "corpus.json"),
      `${JSON.stringify({
        schema: "samedaydesk.caller-example-corpus.v1",
        id: "runtime-fresh",
        cases: [
          {
            id: "fresh",
            jobId: "vendor-budget-impact",
            dir: "fresh",
            inputs: { before: "before.json", after: "after.json" },
          },
        ],
      })}\n`,
    );
    const outDir = mkdtempSync(join(tmpdir(), "w5-m11-runtime-out-"));
    const r = runCli(["run", "--corpus", work, "--out-dir", outDir]);
    assert.equal(r.status, 0, r.stderr + r.stdout);
    const body = JSON.parse(r.stdout);
    assert.equal(body.results[0].independentlyValidCaller, true);
    assert.equal(body.results[0].analysis, "delivered");
    assert.ok(body.results[0].domain.fieldKeys.includes("runtime-batch"));
    assert.ok(body.results[0].domain.actionKinds.includes("normalize-unit-before-budgeting"));

    const shipped = runCorpus(DEFAULT_CORPUS);
    const raise = shipped.results.find((x) => x.id === "ops-desk-rate-raise");
    const cmp = compareDomain(raise.domain, body.results[0].domain);
    assert.equal(cmp.comparable, true);
    assert.equal(cmp.meaningful, true);
  });

  it("note-only change is not forced to a new domain result; unlike jobs are not hash-equalized", () => {
    const work = mkdtempSync(join(tmpdir(), "w5-m11-note-"));
    mkdirSync(join(work, "raise"));
    writeFileSync(
      join(work, "raise/before.json"),
      readFileSync(join(DEFAULT_CORPUS, "ops-desk-rate-raise/before.json")),
    );
    const after = JSON.parse(readFileSync(join(DEFAULT_CORPUS, "ops-desk-rate-raise/after.json"), "utf8"));
    after.note = `${after.note} Operator margin comment only.`;
    writeFileSync(join(work, "raise/after.json"), `${JSON.stringify(after, null, 2)}\n`);
    writeFileSync(
      join(work, "corpus.json"),
      `${JSON.stringify({
        schema: "samedaydesk.caller-example-corpus.v1",
        id: "note-noise",
        cases: [
          {
            id: "raise",
            jobId: "vendor-budget-impact",
            dir: "raise",
            inputs: { before: "before.json", after: "after.json" },
          },
        ],
      })}\n`,
    );
    const noisy = runCorpus(work);
    const shipped = runCorpus(DEFAULT_CORPUS);
    const raise = shipped.results.find((x) => x.id === "ops-desk-rate-raise");
    const harbor = shipped.results.find((x) => x.id === "harbor-feed-delta");
    assert.equal(noisy.results[0].analysis, "delivered");
    const sameDomain = compareDomain(raise.domain, noisy.results[0].domain);
    assert.equal(sameDomain.comparable, true);
    assert.equal(sameDomain.meaningful, false);
    const unlike = compareDomain(raise.domain, harbor.domain);
    assert.equal(unlike.comparable, false);
    assert.equal(unlike.reason, "unlike-jobs");
    if (raise.engineDigest && noisy.results[0].engineDigest) {
      // Path-including engine digests may differ even when domain matches. Do not force equality.
      assert.equal(typeof raise.engineDigest, "string");
    }
  });
});
