/**
 * Independent lockfile pin witness for yargs/yargs package-lock.json.
 * Compares name+version+integrity+resolved. Does not import kit engines.
 */
const HTML_RE = /^\s*(<!DOCTYPE\s+html|<html[\s>]|<head[\s>]|<body[\s>])/i;
const YARN_RE = /^\s*(?:#\s*)?yarn lockfile v1\b/i;
const PNPM_RE = /^\s*lockfileVersion:\s*['"]?\d+/m;
const BUN_RE = /^\s*bun-lockfile|\bbun\.lock\b/i;

function asText(input) {
  if (input == null) return "";
  if (typeof input === "string") return input;
  if (Buffer.isBuffer(input)) return input.toString("utf8");
  if (typeof input === "object" && typeof input.text === "string") return input.text;
  if (typeof input === "object") return JSON.stringify(input);
  return String(input);
}

function stripBom(text) {
  return String(text || "").replace(/^\uFEFF/, "");
}

function isPlainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function norm(value) {
  if (value == null) return null;
  const text = String(value).trim();
  return text === "" ? null : text;
}

function nameFromPackagesKey(key) {
  if (!key) return null;
  const marker = "node_modules/";
  const idx = key.lastIndexOf(marker);
  const rest = idx >= 0 ? key.slice(idx + marker.length) : key;
  return rest || null;
}

function packageJsonOnly(doc) {
  if (!isPlainObject(doc)) return false;
  if (typeof doc.lockfileVersion === "number") return false;
  if (isPlainObject(doc.packages)) return false;
  const deps = doc.dependencies;
  if (isPlainObject(deps)) {
    const values = Object.values(deps);
    if (values.length > 0 && values.every((v) => typeof v === "string")) return true;
  }
  if (typeof doc.name === "string" && (doc.scripts || doc.devDependencies || doc.main)) return true;
  if (typeof doc.name === "string" && typeof doc.version === "string" && !doc.packages && !doc.dependencies) {
    return true;
  }
  return false;
}

function refused(code, message, extra = {}) {
  return {
    ok: false,
    refused: true,
    fact: message,
    code,
    changed: [],
    unchanged: [],
    added: [],
    removed: [],
    unknown: [],
    ...extra,
  };
}

function pinFromEntry(id, entry) {
  const name = norm(entry.name) || nameFromPackagesKey(id);
  return {
    id,
    name,
    version: norm(entry.version),
    integrity: norm(entry.integrity),
    resolved: norm(entry.resolved),
    missingIntegrity: norm(entry.integrity) == null,
  };
}

function collectPins(doc) {
  const pins = new Map();
  if (isPlainObject(doc.packages)) {
    for (const [id, entry] of Object.entries(doc.packages)) {
      if (id === "") continue;
      if (!isPlainObject(entry)) continue;
      if (entry.link === true) continue;
      pins.set(id, pinFromEntry(id, entry));
    }
    return { mapSource: "packages", pins };
  }
  function walk(deps, prefix) {
    if (!isPlainObject(deps)) return;
    for (const [name, entry] of Object.entries(deps)) {
      if (!isPlainObject(entry)) continue;
      const id = prefix ? `${prefix}/node_modules/${name}` : `node_modules/${name}`;
      pins.set(id, pinFromEntry(id, { ...entry, name }));
      if (entry.dependencies) walk(entry.dependencies, id);
    }
  }
  walk(doc.dependencies, "");
  return { mapSource: "dependencies", pins };
}

function classifyText(text, label) {
  const raw = stripBom(text);
  if (!raw.trim()) {
    return { refuse: refused("missing-input", `${label} is empty`, { label }) };
  }
  if (HTML_RE.test(raw)) {
    return { refuse: refused("html-input", `${label} is HTML, not package-lock.json`, { label }) };
  }
  if (YARN_RE.test(raw) || /^\s*#\s*THIS IS AN AUTOGENERATED FILE.*yarn/i.test(raw)) {
    return { refuse: refused("yarn-lockfile", `${label} is yarn.lock, not npm package-lock.json`, { label }) };
  }
  if (PNPM_RE.test(raw) && !raw.trimStart().startsWith("{")) {
    return { refuse: refused("pnpm-lockfile", `${label} is pnpm-lock.yaml, not npm package-lock.json`, { label }) };
  }
  if (BUN_RE.test(raw) && !raw.trimStart().startsWith("{")) {
    return { refuse: refused("bun-lockfile", `${label} is a bun lock, not npm package-lock.json`, { label }) };
  }
  let doc;
  try {
    doc = JSON.parse(raw);
  } catch (err) {
    return { refuse: refused("parse-error", `${label} is not JSON: ${err.message}`, { label }) };
  }
  if (!isPlainObject(doc)) {
    return { refuse: refused("not-a-lockfile", `${label} is not a lockfile object`, { label }) };
  }
  if (packageJsonOnly(doc)) {
    return { refuse: refused("package-json-only", `${label} looks like package.json, not package-lock.json`, { label }) };
  }
  if (typeof doc.lockfileVersion !== "number") {
    return { refuse: refused("not-a-lockfile", `${label} is not an npm lockfile (missing lockfileVersion)`, { label }) };
  }
  if (doc.lockfileVersion !== 2 && doc.lockfileVersion !== 3) {
    return {
      refuse: refused("unsupported-lockfile-version", `lockfileVersion ${doc.lockfileVersion} is not 2 or 3`, {
        label,
        lockfileVersion: doc.lockfileVersion,
      }),
    };
  }
  if (!isPlainObject(doc.packages) && !isPlainObject(doc.dependencies)) {
    return {
      refuse: refused("missing-packages-and-dependencies", "lockfile has neither packages nor dependencies maps", {
        label,
      }),
    };
  }
  const extracted = collectPins(doc);
  const root = isPlainObject(doc.packages) && isPlainObject(doc.packages[""]) ? doc.packages[""] : null;
  return {
    doc,
    lockfileVersion: doc.lockfileVersion,
    rootName: typeof doc.name === "string" ? doc.name : root?.name ?? null,
    rootVersion: typeof doc.version === "string" ? doc.version : root?.version ?? null,
    ...extracted,
  };
}

function pinFieldsEqual(a, b) {
  return a.name === b.name && a.version === b.version && a.integrity === b.integrity && a.resolved === b.resolved;
}

function changeKinds(a, b) {
  const fields = ["name", "version", "integrity", "resolved"];
  return fields.filter((f) => a[f] !== b[f]);
}

function publicPin(pin) {
  return {
    id: pin.id,
    name: pin.name,
    version: pin.version,
    integrity: pin.integrity,
    resolved: pin.resolved,
    missingIntegrity: pin.missingIntegrity,
  };
}

function usedFilter(used) {
  if (used == null) return null;
  if (Array.isArray(used)) {
    return new Set(used.map((item) => (typeof item === "string" ? item : item?.id)).filter(Boolean));
  }
  if (typeof used === "object") {
    const ids = used.ids || used.pins || used.used;
    if (Array.isArray(ids)) return usedFilter(ids);
  }
  return null;
}

/**
 * @param {string|object|Buffer} before
 * @param {string|object|Buffer} after
 * @param {string[]|{ids?: string[]}|undefined} used
 * @returns {{fact: string, changed: object[], unchanged: string[], added: object[], removed: object[], unknown: object[]}}
 */
export function witness(before, after, used) {
  const beforeText = asText(before);
  const afterText = asText(after);
  const b = classifyText(beforeText, "before");
  if (b.refuse) return b.refuse;
  const a = classifyText(afterText, "after");
  if (a.refuse) return a.refuse;

  const focus = usedFilter(used);
  const ids = [...new Set([...b.pins.keys(), ...a.pins.keys()])].sort();
  const added = [];
  const removed = [];
  const changed = [];
  const unchanged = [];
  const unknown = [];

  for (const id of ids) {
    if (focus && !focus.has(id)) continue;
    const bp = b.pins.get(id);
    const ap = a.pins.get(id);
    if (!bp && ap) {
      added.push(publicPin(ap));
      continue;
    }
    if (bp && !ap) {
      removed.push(publicPin(bp));
      continue;
    }
    if (bp.missingIntegrity || ap.missingIntegrity) {
      unknown.push({
        id,
        reason: "missing-integrity",
        before: publicPin(bp),
        after: publicPin(ap),
      });
    }
    if (pinFieldsEqual(bp, ap)) {
      unchanged.push(id);
      continue;
    }
    changed.push({
      id,
      name: ap.name || bp.name,
      changeKinds: changeKinds(bp, ap),
      before: publicPin(bp),
      after: publicPin(ap),
    });
  }

  if (focus) {
    for (const id of focus) {
      if (!b.pins.has(id) && !a.pins.has(id)) {
        unknown.push({ id, reason: "used-pin-absent-from-both-lockfiles" });
      }
    }
  }

  const hasDelta = added.length + removed.length + changed.length > 0;
  const missingIntegrity = unknown.filter((u) => u.reason === "missing-integrity").length;
  const status = missingIntegrity > 0 ? "partial" : hasDelta ? "actionable" : "informational";
  const rootChanged =
    norm(b.rootName) !== norm(a.rootName) || norm(b.rootVersion) !== norm(a.rootVersion)
      ? { before: { name: b.rootName, version: b.rootVersion }, after: { name: a.rootName, version: a.rootVersion } }
      : null;

  const fact = [
    `${b.rootName || "lockfile"}@${b.rootVersion || "?"} → ${a.rootName || "lockfile"}@${a.rootVersion || "?"}`,
    `lockfileVersion ${b.lockfileVersion}→${a.lockfileVersion}`,
    `${added.length} added, ${removed.length} removed, ${changed.length} changed, ${unchanged.length} unchanged registry pins`,
    rootChanged
      ? "root packages[\"\"] / lockfile name+version is the local project, not a registry pin"
      : "root project identity unchanged",
  ].join("; ");

  return {
    ok: true,
    refused: false,
    fact,
    status,
    equality: "name+version+integrity+resolved",
    lockfileVersion: { before: b.lockfileVersion, after: a.lockfileVersion },
    mapSource: { before: b.mapSource, after: a.mapSource },
    root: {
      before: { name: b.rootName, version: b.rootVersion },
      after: { name: a.rootName, version: a.rootVersion },
      treatedAsRegistryPin: false,
      changed: Boolean(rootChanged),
    },
    counts: {
      beforePins: focus ? [...b.pins.keys()].filter((id) => focus.has(id)).length : b.pins.size,
      afterPins: focus ? [...a.pins.keys()].filter((id) => focus.has(id)).length : a.pins.size,
      added: added.length,
      removed: removed.length,
      changed: changed.length,
      unchanged: unchanged.length,
      unknown: unknown.length,
    },
    changed,
    unchanged,
    added,
    removed,
    unknown,
  };
}

export default witness;
